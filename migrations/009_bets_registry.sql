-- Реестр ставок и диалоги бота (specs/реестр-ставок.md).
-- 1) Оповещения получают номер alert_id (последовательность; резервируется до
--    отправки, при неудаче номер сгорает) и время начала матча kickoff_at.
--    Таблица live_alerts_sent маленькая, ADD COLUMN с identity блокирует её на миг.
-- 2) bets — реестр ставок; bot_dialogs — шаг диалога и последний обработанный update_id.

ALTER TABLE live_alerts_sent ADD COLUMN alert_id INTEGER GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE live_alerts_sent ADD CONSTRAINT live_alerts_sent_alert_id_key UNIQUE (alert_id);
ALTER TABLE live_alerts_sent ADD COLUMN kickoff_at TIMESTAMPTZ;

CREATE TABLE bets (
    bet_id            BIGINT      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    alert_id          INTEGER     REFERENCES live_alerts_sent (alert_id) ON DELETE RESTRICT,
    fixture_id        INTEGER     NOT NULL,
    market            TEXT        NOT NULL CHECK (market IN ('TB', 'ITB1', 'ITB2')),
    line              NUMERIC(5, 2) NOT NULL CHECK (line > 0),
    odds              NUMERIC(7, 3) NOT NULL CHECK (odds > 1),
    stake             NUMERIC(12, 2) NOT NULL CHECK (stake > 0),
    kickoff_at        TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    status            TEXT        NOT NULL DEFAULT 'open'
                      CHECK (status IN ('open', 'won', 'half_won', 'push', 'half_lost', 'lost', 'void')),
    goals_home        SMALLINT,
    goals_away        SMALLINT,
    settled_at        TIMESTAMPTZ,
    profit            NUMERIC(12, 3),
    stuck_notified_at TIMESTAMPTZ
);

COMMENT ON TABLE bets IS
    'Реестр ставок владельца. Результат (status, profit) проставляет задание settle_bets после матча.';

CREATE INDEX idx_bets_status ON bets (status);
CREATE INDEX idx_bets_kickoff ON bets (kickoff_at);
CREATE INDEX idx_bets_fixture ON bets (fixture_id);

CREATE TABLE bot_dialogs (
    chat_id        BIGINT      PRIMARY KEY,
    step           TEXT,
    payload        JSONB       NOT NULL DEFAULT '{}'::jsonb,
    last_update_id BIGINT,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
